import SwiftUI

struct AdminMaintenanceWorkOrdersCard: View {
    let viewModel: AdminMaintenanceDetailViewModel

    var body: some View {
        AdminCard(title: "Work orders", systemImage: "wrench.and.screwdriver") {
            let orders = viewModel.workOrders
            if !orders.isEmpty {
                VStack(spacing: 0) {
                    ForEach(orders) { order in
                        AdminMaintenanceWorkOrderRow(order: order)
                        if order.id != orders.last?.id { Divider() }
                    }
                }
            } else if let message = viewModel.workOrdersError {
                AdminSectionNotice(text: message, isError: true)
            } else if viewModel.hasLoaded {
                AdminSectionNotice(text: String(localized: "No work orders generated by this plan."))
            } else {
                ProgressView().frame(maxWidth: .infinity)
            }
        }
    }
}

struct AdminMaintenanceWorkOrderRow: View {
    let order: AdminMaintenanceWorkOrder

    var body: some View {
        HStack(alignment: .top, spacing: 10) {
            VStack(alignment: .leading, spacing: 3) {
                Text(order.title)
                    .font(.subheadline.weight(.semibold))
                    .multilineTextAlignment(.leading)
                    .lineLimit(2)
                if let status = order.status {
                    Label(status.localized, systemImage: status.systemImage)
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }
            }
            Spacer(minLength: 8)
            VStack(alignment: .trailing, spacing: 4) {
                if let priority = order.priority, priority != .unknown {
                    Text(priority.localized)
                        .font(.caption2.weight(.bold))
                        .foregroundStyle(priority == .high ? Color.red : Color.secondary)
                }
                if let date = order.displayDate {
                    Text(date.formatted(.dateTime.month(.abbreviated).day()))
                        .font(.caption2)
                        .foregroundStyle(.secondary)
                }
            }
        }
        .padding(.vertical, 10)
        .opacity(order.isClosed ? 0.65 : 1)
        .accessibilityElement(children: .combine)
    }
}
